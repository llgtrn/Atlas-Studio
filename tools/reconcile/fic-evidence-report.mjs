#!/usr/bin/env node
// fic-evidence-report.mjs -- writes the full-repo FIC domain-evidence report (deliverable 2 of the
// FIC evidence aggregator; docs/doctrines/180-doctrine-world-class-infrastructure-coverage.md section 6).
//
// Runs tools/reconcile/fic-domain-evidence-lib.mjs's computeAllDomainEvidence(...) across every
// domain in docs/_machine/world-class-infrastructure-coverage-v1.json and writes:
//   docs/_machine/reconcile-reports/fic-domain-evidence-<date>.json   (machine-readable, full detail)
//   docs/_machine/reconcile-reports/fic-domain-evidence-<date>.md     (human summary table)
//
// The .md table is sorted so domains whose raw evidence most CONTRADICTS the current hand-assigned
// level float to the top -- that is the highest-value re-review list for a human. "Contradicts" is
// a plain scalar distance between a 0..1 evidence-strength composite (AGREE rate, reachable-code
// rate, tested rate) and the hand-assigned level's rank, NOT a suggested level; domains that cannot
// be evaluated (NOT_MAPPABLE, or mapped to a crate with zero capability-catalog rows) are listed
// separately at the bottom, never silently dropped.
//
// HONESTY (read before trusting this report):
//   - This tool does NOT compute FIC and does NOT move the published FIC percentage (16.36%, 9/55
//     domains at v1.json's current_estimate). That number changes only when a human reviews this
//     evidence and edits v1.json themselves.
//   - This tool does NOT know whether a domain has a real owner, a real contract, real failure
//     semantics, or documented operating ownership -- doc 180 section 2 reserves those judgment
//     calls for humans. It only surfaces mechanical sub-signals (mapping coverage, sync-anchor-v2
//     AGREE/DISAGREE, code reachability, test evidence, crate-doc existence).
//   - "crate doc exists" is a weak proxy for "this crate has SOME documented surface" -- it is NOT
//     a check for a named owner, an operating runbook, or any of doc 180 section 13's ownership
//     fields.
//
// Usage:
//   node tools/reconcile/fic-evidence-report.mjs --date 2026-07-31
//   node tools/reconcile/fic-evidence-report.mjs --date 2026-07-31 --out-dir docs/_machine/reconcile-reports
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { computeAllDomainEvidence, reviewPriority } from './fic-domain-evidence-lib.mjs'

function parseArgs(argv) {
  const opts = { date: null, outDir: join('docs', '_machine', 'reconcile-reports') }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--date') opts.date = argv[++i]
    else if (arg === '--out-dir') opts.outDir = argv[++i]
    else {
      console.error(`fic-evidence-report: unknown argument "${arg}"`)
      process.exit(2)
    }
  }
  if (!opts.date) {
    console.error('fic-evidence-report: --date <YYYY-MM-DD> is required (this script never reads the system clock).')
    process.exit(2)
  }
  return opts
}

function mdEscape(value) {
  return String(value ?? '').replace(/\|/g, '\\|')
}

function fmtPct(value) {
  return value === null || value === undefined ? 'n/a' : `${value}%`
}

function buildMarkdown(result, ranked, date) {
  const evaluable = ranked.filter((r) => r.priority.evaluable)
  const notEvaluable = ranked.filter((r) => !r.priority.evaluable)

  const lines = []
  lines.push(`# FIC Domain Evidence Report -- ${date}`)
  lines.push('')
  lines.push(
    '**This does NOT compute FIC and does NOT move the published FIC percentage.** v1.json\'s ' +
      `current estimate stays exactly what it was (${result.v1_status === 'DESIGN_ESTIMATE_LOCAL_AUDIT_REQUIRED' ? '16.36%, 9/55 domains' : 'see v1.json'}) ` +
      'until a human reviews this evidence and edits v1.json themselves. Every level/state/wave value ' +
      'below is copied read-only from the CURRENT v1.json for side-by-side comparison; this report never ' +
      'writes one.',
  )
  lines.push('')
  lines.push(
    'This tool does NOT know whether a domain has a named owner, a real contract, failure semantics, or ' +
      'documented operating ownership -- doc 180 section 2 reserves those judgment calls for humans. It only ' +
      'surfaces mechanical sub-signals: how many capability_keys map to the domain (and by what method), ' +
      'sync-anchor-v2 AGREE/DISAGREE, code reachability (Tier 1/2), test evidence (Tier 3), and whether the ' +
      'backing crate(s) have a crate doc at all (NOT a full owner/contract/failure-semantics check).',
  )
  lines.push('')
  lines.push(`Generated by \`tools/reconcile/fic-evidence-report.mjs\` from the current sync-anchor-v2 pass. ` + `v1.json as_of_date=${result.v1_as_of_date}, status=${result.v1_status}.`)
  lines.push('')
  lines.push(
    `**${evaluable.length}/${result.domains_total} domain(s) have at least one mapped capability with evidence; ` +
      `${notEvaluable.length} could not be evaluated (see the bottom section).**`,
  )
  lines.push('')
  lines.push('## Domains sorted by review priority (evidence most contradicts hand-assigned level first)')
  lines.push('')
  lines.push(
    '`review_priority` is a plain distance between a 0..1 evidence-strength composite (AGREE rate, ' +
      'reachable-code rate, tested rate) and the hand-assigned level\'s rank -- it is a triage heuristic for ' +
      'sort order only, never a suggested level.',
  )
  lines.push('')
  lines.push('| Domain | Hand level | Mapped caps | AGREE% | Reachable% | Tested% | Crate doc | Direction | Priority |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const { domain, priority } of evaluable) {
    const docsPresent = Object.values(domain.crate_doc).filter(Boolean).length
    const docsTotal = Object.keys(domain.crate_doc).length
    lines.push(
      `| ${mdEscape(domain.key)} | ${domain.hand_assigned.level} | ${domain.mapped_capabilities.total} | ` +
        `${fmtPct(domain.sync_anchor_v2?.agree_percent)} | ${fmtPct(domain.code_reachability?.reachable_percent)} | ` +
        `${fmtPct(domain.test_evidence?.tested_percent)} | ${docsPresent}/${docsTotal} | ${priority.direction} | ` +
        `${priority.contradiction_score} |`,
    )
  }
  lines.push('')
  lines.push('## Domains that could not be evaluated')
  lines.push('')
  lines.push(
    'These either have no defensible crate/domain-field mapping in the current capability catalog ' +
      '(`NOT_MAPPABLE`) or map to crate(s) whose shard currently has zero capability-catalog rows ' +
      '(`MAPPED_ZERO_CAPABILITIES`) -- both are honest gaps, not tool failures.',
  )
  lines.push('')
  lines.push('| Domain | Hand level | Reason | Note |')
  lines.push('| --- | --- | --- | --- |')
  for (const { domain, priority } of notEvaluable) {
    lines.push(
      `| ${mdEscape(domain.key)} | ${domain.hand_assigned.level} | ${priority.reason} | ` +
        `${mdEscape(domain.mapping.note ?? (domain.backing_crates.length ? `mapped via ${domain.mapping.method} to [${domain.backing_crates.join(', ')}] but 0 capability rows found` : ''))} |`,
    )
  }
  lines.push('')
  return `${lines.join('\n')}\n`
}

function main() {
  const root = process.cwd()
  const opts = parseArgs(process.argv.slice(2))

  const result = computeAllDomainEvidence(root)
  const ranked = result.per_domain
    .map((domain) => ({ domain, priority: reviewPriority(domain) }))
    .sort((a, b) => {
      if (a.priority.evaluable !== b.priority.evaluable) return a.priority.evaluable ? -1 : 1
      if (!a.priority.evaluable) return a.domain.key.localeCompare(b.domain.key)
      return b.priority.contradiction_score - a.priority.contradiction_score
    })

  mkdirSync(opts.outDir, { recursive: true })
  const jsonPath = join(opts.outDir, `fic-domain-evidence-${opts.date}.json`)
  const mdPath = join(opts.outDir, `fic-domain-evidence-${opts.date}.md`)

  const jsonOut = {
    ...result,
    per_domain_ranked_by_review_priority: ranked.map(({ domain, priority }) => ({ ...domain, review_priority: priority })),
  }
  writeFileSync(jsonPath, `${JSON.stringify(jsonOut, null, 2)}\n`)
  writeFileSync(mdPath, buildMarkdown(result, ranked, opts.date))

  console.log(`fic-evidence-report: wrote ${jsonPath}, ${mdPath}`)
  console.log(
    `  ${ranked.filter((r) => r.priority.evaluable).length}/${result.domains_total} domain(s) evaluable; ` +
      'this does NOT compute FIC and does NOT move the published FIC percentage -- see the doc header.',
  )
}

main()
